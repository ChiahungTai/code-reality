//! CR-16: cargo features for the rust producer (`--config-path` wiring).
//!
//! P-A: `[rust]` profile parsing (global `features` / authoritative
//! `features_by_root` / mutual exclusion / unknown-key / typo'd root key
//! at build time / unknown FEATURE name — the review-adoption
//! pre-validation spawns `cargo metadata` per featured root BEFORE any
//! scip spawn and fails loud naming the typo and the legal candidates).
//! P-B: end-to-end with a REAL rust-analyzer — the
//! feature-gated file enters the index only under configured features
//! (the no-features control is the pre-CR-16 face: the ROOT-09 exact
//! gate fails loud, nothing publishes). P-C: the features ride the
//! identity body's domain extras — fresh after build, stale on a
//! profile-only feature change (F6). P-D: the build report discloses
//! the effective per-root features. P-M: multi-workspace per-root
//! injection (real ra, multi_rust_build.rs conventions) — each listed
//! root's gated file enters, an unlisted root keeps the default face,
//! and a single root's feature change flips freshness.
//!
//! The real-ra tests serialize on one mutex: each fixture is a fresh
//! tempdir (no shared cargo target dir), so concurrent spawns pay N
//! cold workspace loads for nothing.

mod support;

use code_reality::profile::{Profile, load_profile};
use std::path::PathBuf;
use std::sync::{Mutex, MutexGuard};

static RA_LOCK: Mutex<()> = Mutex::new(());

fn ra_lock() -> MutexGuard<'static, ()> {
    RA_LOCK.lock().unwrap_or_else(|e| e.into_inner())
}

/// Mini feature-gated crate at the repo root (single-root auto mode →
/// the "." root). Cargo.lock is generated by the REAL cargo BEFORE any
/// identity capture — otherwise rust-analyzer's own cargo metadata call
/// would mint the lock mid-build and trip the capture A/B drift guard
/// ("source identity/policy changed during production").
fn feat_lab(profile_toml: Option<&str>) -> (PathBuf, tempfile::TempDir) {
    let t = tempfile::tempdir().unwrap();
    let repo = t.path().join("repo");
    support::write(
        &repo,
        "Cargo.toml",
        "[package]\nname = \"featfix\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[features]\nextra = []\n",
    );
    support::write(
        &repo,
        "src/lib.rs",
        "#[cfg(feature = \"extra\")]\npub mod gated;\n\npub fn base() -> i32 { 1 }\n",
    );
    support::write(&repo, "src/gated.rs", "pub fn gated_fn() -> i32 { 2 }\n");
    let st = std::process::Command::new("cargo")
        .args(["generate-lockfile"])
        .current_dir(&repo)
        .status()
        .expect("cargo on PATH");
    assert!(st.success(), "cargo generate-lockfile failed");
    if let Some(text) = profile_toml {
        support::write(&repo, ".code-reality.toml", text);
    }
    support::git_init(&repo);
    (repo, t)
}

fn parse_ok(text: &str) -> Profile {
    let t = tempfile::tempdir().unwrap();
    support::write(t.path(), ".code-reality.toml", text);
    load_profile(t.path()).unwrap().expect("profile present")
}

fn parse_err(text: &str) -> String {
    let t = tempfile::tempdir().unwrap();
    support::write(t.path(), ".code-reality.toml", text);
    load_profile(t.path()).unwrap_err()
}

// ---------- P-A: profile parsing ----------

#[test]
fn pa_global_features_parse() {
    let p = parse_ok("[rust]\nfeatures = [\"python\", \"extra\"]\n");
    assert_eq!(
        p.rust_features,
        Some(vec!["python".to_string(), "extra".to_string()])
    );
    assert!(p.rust_features_by_root.is_none());
}

#[test]
fn pa_by_root_features_parse() {
    let p = parse_ok("[rust.features_by_root]\n\"crates/a\" = [\"x\"]\n\"crates/b\" = [\"y\", \"z\"]\n");
    assert!(p.rust_features.is_none());
    assert_eq!(
        p.rust_features_by_root,
        Some(vec![
            ("crates/a".to_string(), vec!["x".to_string()]),
            ("crates/b".to_string(), vec!["y".to_string(), "z".to_string()]),
        ])
    );
}

#[test]
fn pa_features_and_by_root_are_mutually_exclusive() {
    let err = parse_err("[rust]\nfeatures = [\"a\"]\n[rust.features_by_root]\n\"x\" = [\"b\"]\n");
    assert!(err.contains("互斥"), "{err}");
}

#[test]
fn pa_unknown_rust_key_fails_loud() {
    let err = parse_err("[rust]\nfeaturz = [\"a\"]\n");
    assert!(err.contains("[rust] 含未知鍵"), "{err}");
    assert!(err.contains("'featurz'"), "{err}");
}

#[test]
fn pa_no_rust_section_keeps_fields_none() {
    let p = parse_ok("exclude = [\"dist/\"]\n");
    assert!(p.rust_features.is_none());
    assert!(p.rust_features_by_root.is_none());
}

#[test]
fn pa_by_root_key_off_any_resolved_root_fails_build() {
    // The typo'd root key fails loud at build staging (before any
    // producer spawn) — a key that matches no resolved root would
    // otherwise silently inject nothing.
    let (repo, _t) = feat_lab(Some(
        "[rust.features_by_root]\n\"typo-root\" = [\"extra\"]\n",
    ));
    let out = code_reality::build::run(&["build", "--repo", &repo.to_string_lossy()]);
    assert_eq!(
        out.exit_code, 2,
        "typo'd root key fails loud: {} {}",
        out.stdout, out.stderr
    );
    assert!(out.stderr.contains("typo-root"), "{}", out.stderr);
    assert!(
        out.stderr.contains("不屬任何 resolved root"),
        "{}",
        out.stderr
    );
}

#[test]
fn pa_unknown_feature_fails_loud_before_spawn() {
    // Review adoption (HIGH): a typo'd feature name is silent to
    // rust-analyzer; validation runs cargo metadata against the root's
    // real feature universe BEFORE any scip spawn and fails loud (Env →
    // exit 2) naming the unknown name and the legal candidates. No ra is
    // involved — no ra lock.
    let (repo, _t) = feat_lab(Some("[rust]\nfeatures = [\"extrae\"]\n"));
    let out = code_reality::build::run(&["build", "--repo", &repo.to_string_lossy()]);
    assert_eq!(
        out.exit_code, 2,
        "unknown feature fails loud: {} {}",
        out.stdout, out.stderr
    );
    assert!(out.stderr.contains("extrae"), "{}", out.stderr);
    assert!(out.stderr.contains("不存在"), "{}", out.stderr);
    // The candidate face pins the LEGAL name: 'extra' (quote-closed) is
    // not a substring of the unknown 'extrae'.
    assert!(out.stderr.contains("'extra'"), "{}", out.stderr);
    assert!(
        !support::slot_of(&repo).exists(),
        "nothing published on the unknown feature"
    );
}


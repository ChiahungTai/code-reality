#[test]
fn pd_report_discloses_effective_features() {
    let _ra = ra_lock();
    let (repo, _t) = feat_lab(Some("[rust]\nfeatures = [\"extra\"]\n"));
    let out = code_reality::build::run(&["build", "--repo", &repo.to_string_lossy(), "--json"]);
    assert_eq!(out.exit_code, 0, "build: {} {}", out.stdout, out.stderr);
    let v: serde_json::Value = serde_json::from_str(out.stdout.trim())
        .unwrap_or_else(|e| panic!("report JSON ({e}): {}", out.stdout));
    let notes = v["notes"].as_array().unwrap();
    assert!(
        notes.iter().any(|n| n
            .as_str()
            .is_some_and(|s| s.contains("rust features") && s.contains("extra"))),
        "features disclosure note in report notes: {notes:?}"
    );
}

// ---------- P-M: multi-workspace per-root injection (real ra) ----------

/// Dual-workspace feature lab (multi_rust_build.rs conventions, real
/// rust-analyzer): two sibling package-workspace roots `alpha`/`beta`,
/// each gating `src/gated.rs` behind its OWN feature name. Cargo.lock is
/// generated by the REAL cargo BEFORE any identity capture (the feat_lab
/// contract), and the config-mode profile pins `rust_projects`.
fn multi_feat_lab(profile_toml: &str) -> (PathBuf, tempfile::TempDir) {
    let t = tempfile::tempdir().unwrap();
    let repo = t.path().join("repo");
    for (root, feat) in [("alpha", "alpha_extra"), ("beta", "beta_extra")] {
        support::write(
            &repo,
            &format!("{root}/Cargo.toml"),
            &format!(
                "[package]\nname = \"{root}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[features]\n{feat} = []\n\n[workspace]\n"
            ),
        );
        support::write(
            &repo,
            &format!("{root}/src/lib.rs"),
            &format!(
                "#[cfg(feature = \"{feat}\")]\npub mod gated;\n\npub fn base() -> i32 {{ 1 }}\n"
            ),
        );
        support::write(
            &repo,
            &format!("{root}/src/gated.rs"),
            "pub fn gated_fn() -> i32 { 2 }\n",
        );
        let st = std::process::Command::new("cargo")
            .args(["generate-lockfile"])
            .current_dir(repo.join(root))
            .status()
            .expect("cargo on PATH");
        assert!(st.success(), "cargo generate-lockfile failed for {root}");
    }
    support::write(&repo, ".code-reality.toml", profile_toml);
    support::git_init(&repo);
    (repo, t)
}

#[test]
fn pm_dual_root_by_root_features_index_each_gated_file() {
    let _ra = ra_lock();
    let (repo, _t) = multi_feat_lab(
        "rust_projects = [\"alpha\", \"beta\"]\n\n[rust.features_by_root]\n\"alpha\" = [\"alpha_extra\"]\n\"beta\" = [\"beta_extra\"]\n",
    );
    let out = code_reality::build::run(&["build", "--repo", &repo.to_string_lossy(), "--json"]);
    assert_eq!(
        out.exit_code, 0,
        "dual-root features build: {} {}",
        out.stdout, out.stderr
    );
    let docs = support::slot_docs(&repo);
    assert_eq!(
        docs,
        vec![
            "alpha/src/gated.rs".to_string(),
            "alpha/src/lib.rs".to_string(),
            "beta/src/gated.rs".to_string(),
            "beta/src/lib.rs".to_string(),
        ],
        "each root's gated doc indexed, git-root-relative: {docs:?}"
    );
    // P-D face, per-root: ONE note disclosing both roots' injections.
    let v: serde_json::Value = serde_json::from_str(out.stdout.trim())
        .unwrap_or_else(|e| panic!("report JSON ({e}): {}", out.stdout));
    let notes = v["notes"].as_array().unwrap();
    assert!(
        notes.iter().any(|n| n.as_str().is_some_and(|s| {
            s.contains("rust features")
                && s.contains("alpha=[alpha_extra]")
                && s.contains("beta=[beta_extra]")
        })),
        "per-root disclosure note: {notes:?}"
    );

    // F6 face, per-root: changing ONE root's feature list (profile-only,
    // zero source touch) flips freshness stale.
    let fresh = code_reality::freshness::run(&[
        "freshness",
        "--repo",
        &repo.to_string_lossy(),
        "--json",
    ]);
    assert_eq!(
        fresh.exit_code, 0,
        "fresh after build: {} {}",
        fresh.stdout, fresh.stderr
    );
    support::write(
        &repo,
        ".code-reality.toml",
        "rust_projects = [\"alpha\", \"beta\"]\n\n[rust.features_by_root]\n\"alpha\" = [\"alpha_extra\", \"alpha_second\"]\n\"beta\" = [\"beta_extra\"]\n",
    );
    let stale = code_reality::freshness::run(&[
        "freshness",
        "--repo",
        &repo.to_string_lossy(),
        "--json",
    ]);
    assert_eq!(
        stale.exit_code, 1,
        "single-root feature change is stale: {} {}",
        stale.stdout, stale.stderr
    );
    let v: serde_json::Value = serde_json::from_str(stale.stdout.trim())
        .unwrap_or_else(|e| panic!("verdict JSON ({e}): {}", stale.stdout));
    assert_eq!(v["fresh"], serde_json::json!(false), "{v}");
}

#[test]
fn pm_unlisted_root_default_keeps_gated_file_out() {
    let _ra = ra_lock();
    // by_root is authoritative: beta is not listed → injects nothing →
    // its gated file stays out of the index. beta's gated file is
    // profile-excluded so the absence is LEGAL under the per-root
    // coverage gate — the face under test is per-root injection
    // correctness, not gate semantics.
    let (repo, _t) = multi_feat_lab(
        "rust_projects = [\"alpha\", \"beta\"]\nexclude = [\"beta/src/gated.rs\"]\n\n[rust.features_by_root]\n\"alpha\" = [\"alpha_extra\"]\n",
    );
    let out = code_reality::build::run(&["build", "--repo", &repo.to_string_lossy()]);
    assert_eq!(
        out.exit_code, 0,
        "unlisted root must converge without any gate error: {} {}",
        out.stdout, out.stderr
    );
    let docs = support::slot_docs(&repo);
    assert_eq!(
        docs,
        vec![
            "alpha/src/gated.rs".to_string(),
            "alpha/src/lib.rs".to_string(),
            "beta/src/lib.rs".to_string(),
        ],
        "alpha's injection opens its gated doc; beta keeps the default face: {docs:?}"
    );
}

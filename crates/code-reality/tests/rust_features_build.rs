#[test]
fn pb_features_open_gated_file() {
    let _ra = ra_lock();
    let (repo, _t) = feat_lab(Some("[rust]\nfeatures = [\"extra\"]\n"));
    let out = code_reality::build::run(&["build", "--repo", &repo.to_string_lossy(), "--json"]);
    assert_eq!(out.exit_code, 0, "features build: {} {}", out.stdout, out.stderr);
    let docs = support::slot_docs(&repo);
    assert!(
        docs.contains(&"src/lib.rs".to_string()),
        "base doc indexed: {docs:?}"
    );
    assert!(
        docs.contains(&"src/gated.rs".to_string()),
        "feature-gated doc indexed under [rust] features: {docs:?}"
    );
}

#[test]
fn pb_without_features_gated_file_stays_out() {
    let _ra = ra_lock();
    let (repo, _t) = feat_lab(None);
    // Pre-CR-16 face, unchanged: without [rust] features the gated file
    // never reaches the index. In single-root auto mode the governed
    // walk {lib.rs, gated.rs} vs produced {lib.rs} mismatch trips the
    // loud CR-RUST-ROOT-09 exact gate — and nothing publishes.
    let out = code_reality::build::run(&["build", "--repo", &repo.to_string_lossy()]);
    assert_eq!(
        out.exit_code, 2,
        "no-features build fails loud: {} {}",
        out.stdout, out.stderr
    );
    assert!(out.stderr.contains("CR-RUST-ROOT-09"), "{}", out.stderr);
    assert!(
        out.stderr.contains("src/gated.rs"),
        "walk−index names the gated doc: {}",
        out.stderr
    );
    assert!(
        !support::slot_of(&repo).exists(),
        "nothing published on the coverage hole"
    );
}

// ---------- P-C: identity / F6 ----------

#[test]
fn pc_features_enter_identity_and_flip_freshness() {
    let _ra = ra_lock();
    let (repo, _t) = feat_lab(Some("[rust]\nfeatures = [\"extra\"]\n"));
    let out = code_reality::build::run(&["build", "--repo", &repo.to_string_lossy()]);
    assert_eq!(out.exit_code, 0, "build: {} {}", out.stdout, out.stderr);
    // The freshness re-evaluation must run the SAME features helper as
    // the stamp face — if only the stamp side folded the extras in,
    // this fresh check would false-stale.
    let fresh = code_reality::freshness::run(&[
        "freshness",
        "--repo",
        &repo.to_string_lossy(),
        "--json",
    ]);
    assert_eq!(
        fresh.exit_code, 0,
        "features build answers fresh: {} {}",
        fresh.stdout, fresh.stderr
    );

    // Profile-only change (zero source touch): the features are part of
    // the identity body, so the verdict must flip stale.
    support::write(
        &repo,
        ".code-reality.toml",
        "[rust]\nfeatures = [\"extra\", \"dummy2\"]\n",
    );
    let stale = code_reality::freshness::run(&[
        "freshness",
        "--repo",
        &repo.to_string_lossy(),
        "--json",
    ]);
    assert_eq!(
        stale.exit_code, 1,
        "feature change is stale: {} {}",
        stale.stdout, stale.stderr
    );
    let v: serde_json::Value = serde_json::from_str(stale.stdout.trim())
        .unwrap_or_else(|e| panic!("verdict JSON ({e}): {}", stale.stdout));
    assert_eq!(v["fresh"], serde_json::json!(false), "{v}");
}

